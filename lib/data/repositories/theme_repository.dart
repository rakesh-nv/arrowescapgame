  static ThemeModel _theme({
    required String id,
    required String name,
    required String category,
    required ThemeTier tier,
    required bool dark,
    required List<Color> bg,
    required Color arrow,
    required Color head,
    required Color accent,
    required Color text,
    Color? board,
    Color? dots,
    List<Color>? palette,
  }) {
    return ThemeModel(
      id: id,
      name: name,
      category: category,
      tier: tier,
      backgroundColor: bg.first,
      surfaceColor: dark
          ? Color.lerp(bg.first, Colors.white, 0.08)!
          : Colors.white,
      arrowColor: arrow,
      headColor: head,
      accentColor: accent,
      textColor: text,
      particleColor: accent,
      isDark: dark,
      backgroundGradient: bg,
      boardColor:
          board ?? (dark ? const Color(0x0FFFFFFF) : const Color(0x80FFFFFF)),
      dotColor: dots,
      arrowPalette: palette,
    );
  }

  static ThemeModel getById(String id) {
    return allThemes.firstWhere(
      (t) => t.id == id,
      orElse: () => allThemes.first,
    );
  }

  static bool exists(String id) => allThemes.any((t) => t.id == id);

  static List<ThemeModel> byCategory(String category) =>
      allThemes.where((t) => t.category == category).toList();
}
