/// Colours and flavour of one map region. Purely visual: worlds, unlocks and
/// difficulty still come from [DifficultyCurve] and the player's progress.
class MapBiome {
  final BiomeKind kind;
  final String name;

  /// Ground gradient, bottom (entrance) to top (exit) of the region.
  final Color groundBottom;
  final Color groundTop;

  /// Edge terrain (hills, dunes, cliffs, buildings…), far and near layers.
  final Color terrainFar;
  final Color terrainNear;

  final Color trail;
  final Color trailEdge;

  /// River / canyon / lava band crossing the region.
  final Color water;
  final Color waterLight;
  final Color bridge;

  /// Decoration palette: main foliage, secondary foliage, accents.
  final Color decorA;
  final Color decorB;
  final Color decorC;

  /// Banner and gate accent.
  final Color accent;

  final ParticleKind particle;
  final Color particleColor;

  /// Whether the ground is dark (affects text and locked-node contrast).
  final bool dark;

  /// Whether drifting clouds suit the region (open-sky biomes).
  final bool clouds;

  const MapBiome({
    required this.kind,
    required this.name,
    required this.groundBottom,
    required this.groundTop,
    required this.terrainFar,
    required this.terrainNear,
    required this.trail,
    required this.trailEdge,
    required this.water,
    required this.waterLight,
    required this.bridge,
    required this.decorA,
    required this.decorB,
    required this.decorC,
    required this.accent,
    required this.particle,
    required this.particleColor,
    this.dark = false,
    this.clouds = true,
  });

