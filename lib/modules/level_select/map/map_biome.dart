/// Ambient motion drawn over a region.
enum ParticleKind {
  fireflies,
  dust,
  snow,
  bubbles,
  embers,
  neon,
  glints,
  stars,
  rain,
  lanterns,
  petals,
  leaves,
  comets,
  aurora,
  wind,
